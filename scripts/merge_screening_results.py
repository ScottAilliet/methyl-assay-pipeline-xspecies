#!/usr/bin/env python3
"""
merge_screening_results.py
Merge ePCR screening results, DMS sub-scores, and primer annotations
into the master primer atlas Excel file.

Reads:
  - master_primer_assays_atlas.xlsx
    Sheets: All_Primers (391,570 rows), Best_Per_DMR, Summary, DMR_Blocks
  - results_v2.csv (full screening output)
  - results_v2_selected.csv (selected panel, auto-generated by select subcommand)
  - dms_subscores.csv (optional, from compute_dms_subscores.py)
  - primer_annotations.csv (optional, from annotate_primers.py)

Writes:
  - master_atlas_screened_v3.xlsx
    - All_Primers: original columns (minus direction, cleanliness_score, legacy columns)
      + ePCR columns + DMS A-E sub-scores + annotation columns
    - Selected_Panel: all passing primers with all columns
    - Best_Per_DMR, Summary, DMR_Blocks: preserved (direction, cleanliness_score removed)
    - Data_Dictionary: detailed explanation of every column in every sheet

Removed columns:
  - direction: unreliable
  - cleanliness_score: renamed to dms_score (duplicate removed)
  - legacy columns: superseded by ePCR screening

Merge key: assay_id + left_primer + right_primer + template_used
(Each row in the atlas is a unique primer-template combination.)

Usage:
    cd ~/epcr_screening
    python merge_screening_results.py \\
        --atlas master_primer_assays_atlas.xlsx \\
        --results results_v2.csv \\
        --selected results_v2_selected.csv \\
        --dms-subscores dms_subscores.csv \\
        --annotations primer_annotations.csv \\
        --output master_atlas_screened_v3.xlsx

Prerequisites:
    pip install pandas openpyxl xlsxwriter
    Place data_dictionary.py in the same directory.
"""

import argparse
import os
import sys
import time
import pandas as pd

from data_dictionary import build_data_dictionary

# Merge key columns (same names in xlsx and screening CSVs)
KEY_COLS = ['assay_id', 'left_primer', 'right_primer', 'template_used']

# Screening columns to add (renamed with ePCR_ prefix for clarity)
SCR_COLS = {
    'verdict': 'ePCR_verdict',
    'product_count': 'ePCR_product_count',
    'products': 'ePCR_products',
    'error': 'ePCR_error',
    'elapsed_sec': 'ePCR_elapsed_sec',
}

# Columns to remove from all sheets
# direction: unreliable (user instruction)
# cleanliness_score: renamed to dms_score (duplicate removed)
# legacy columns: superseded by ePCR screening
DROP_COLS = [
    'direction',
    'cleanliness_score',
    'sense_meth_mismatch_score',
    'sense_unmeth_mismatch_score',
    'anti_meth_mismatch_score',
    'anti_unmeth_mismatch_score',
    'bowtie_passes_filter',
    'bowtie_intended_genome',
    'mismatch_profile',
    'mismatch_detail',
    'mapping_error_note',
    'has_bowtie_pass',
    'num_pass_bowtie',
    'num_fail_bowtie',
    'num_bowtie_none',
]

# DMS sub-score columns to merge from dms_subscores.csv
DMS_SUBSCORE_COLS = [
    'score_A_tg_near0', 'score_B_bg_near1',
    'score_C_tg_consist', 'score_D_bg_consist',
    'score_E_coverage',
]

# Annotation columns to merge from primer_annotations.csv
ANNOTATION_COLS = [
    'common_variant_score', 'snp_count',
    'segdup_overlap', 'repeat_overlap', 'repeat_family',
]


def make_key(df):
    """Create composite merge key: assay_id|left_primer|right_primer|template_used"""
    parts = []
    for col in KEY_COLS:
        if col in df.columns:
            parts.append(df[col].astype(str).str.strip())
        else:
            parts.append(pd.Series([''] * len(df), index=df.index))
    return parts[0].str.cat(parts[1:], sep='|')


def main():
    parser = argparse.ArgumentParser(
        description="Merge ePCR screening results, DMS sub-scores, and annotations into atlas xlsx")
    parser.add_argument("--atlas", default="master_primer_assays_atlas.xlsx",
                        help="Path to the master atlas xlsx (default: master_primer_assays_atlas.xlsx)")
    parser.add_argument("--results", default="results_v2.csv",
                        help="Path to ePCR screening results CSV (default: results_v2.csv)")
    parser.add_argument("--selected", default="results_v2_selected.csv",
                        help="Path to selected panel CSV (default: results_v2_selected.csv)")
    parser.add_argument("--dms-subscores", default=None,
                        help="Path to DMS sub-scores CSV (optional)")
    parser.add_argument("--annotations", default=None,
                        help="Path to primer annotations CSV (optional)")
    parser.add_argument("--output", default="master_atlas_screened_v3.xlsx",
                        help="Output xlsx path (default: master_atlas_screened_v3.xlsx)")
    args = parser.parse_args()

    t0 = time.time()

    # Check input files
    for f in [args.atlas, args.results, args.selected]:
        if not os.path.exists(f):
            print(f'ERROR: {f} not found', file=sys.stderr)
            sys.exit(1)

    # 1. Read all sheets from master xlsx
    print(f'Reading {args.atlas} ...')
    all_sheets = pd.read_excel(args.atlas, sheet_name=None, engine='openpyxl')
    sheet_names = list(all_sheets.keys())
    print(f'  Sheets: {sheet_names}')

    # 2. Remove dropped columns from all sheets
    for name, df_sheet in all_sheets.items():
        drop_present = [c for c in DROP_COLS if c in df_sheet.columns]
        if drop_present:
            all_sheets[name] = df_sheet.drop(columns=drop_present)
            print(f'  {name}: removed {drop_present}')

    df = all_sheets['All_Primers']
    print(f'  All_Primers: {len(df):,} rows x {len(df.columns)} cols')

    # 3. Read screening results
    print(f'\nReading {args.results} ...')
    df_scr = pd.read_csv(args.results)
    print(f'  {len(df_scr):,} rows x {len(df_scr.columns)} cols')

    # 4. Read selected panel
    print(f'Reading {args.selected} ...')
    df_sel = pd.read_csv(args.selected)
    print(f'  {len(df_sel):,} rows')

    # 5. Build merge keys
    df['_key'] = make_key(df)
    df_scr['_key'] = make_key(df_scr)
    selected_keys = set(make_key(df_sel))

    # 6. Validate: check for duplicate keys in screening results
    n_dup = df_scr['_key'].duplicated().sum()
    if n_dup > 0:
        print(f'  WARNING: {n_dup} duplicate keys in screening CSV, deduplicating (keeping first)')
        df_scr = df_scr.drop_duplicates(subset='_key', keep='first')

    # 7. Validate: check how many screening results match the atlas
    atlas_keys = set(df['_key'])
    scr_matched = df_scr['_key'].isin(atlas_keys).sum()
    scr_unmatched = len(df_scr) - scr_matched
    print(f'\n  Screening results matched to atlas: {scr_matched:,} / {len(df_scr):,}')
    if scr_unmatched > 0:
        print(f'  WARNING: {scr_unmatched} screening results not found in atlas')

    sel_matched = len(selected_keys & atlas_keys)
    print(f'  Selected panel matched to atlas: {sel_matched} / {len(selected_keys)}')

    # 8. Merge screening columns into All_Primers (left join)
    scr_cols_present = [c for c in SCR_COLS if c in df_scr.columns]
    rename_map = {c: SCR_COLS[c] for c in scr_cols_present}

    df = df.merge(
        df_scr[['_key'] + scr_cols_present].rename(columns=rename_map),
        on='_key', how='left'
    )

    # 9. Add selected_for_panel flag
    df['selected_for_panel'] = df['_key'].isin(selected_keys).astype(int)

    # 10. Merge DMS sub-scores (if provided)
    if args.dms_subscores and os.path.exists(args.dms_subscores):
        print(f'\nReading DMS sub-scores from {args.dms_subscores} ...')
        df_dms = pd.read_csv(args.dms_subscores)
        print(f'  {len(df_dms):,} rows')

        # Merge key: cell_type + chrom + dmr_start + dmr_end
        dms_key_cols = ['cell_type', 'chrom', 'dmr_start', 'dmr_end']
        dms_cols_present = [c for c in DMS_SUBSCORE_COLS if c in df_dms.columns]
        if dms_cols_present:
            # Ensure key columns match types
            for c in dms_key_cols:
                df[c] = df[c].astype(str)
                df_dms[c] = df_dms[c].astype(str)
            df = df.merge(
                df_dms[dms_key_cols + dms_cols_present],
                on=dms_key_cols, how='left'
            )
            print(f'  Merged {len(dms_cols_present)} DMS sub-score columns')
        else:
            print(f'  WARNING: no DMS sub-score columns found in {args.dms_subscores}')
    else:
        print(f'\nSkipping DMS sub-scores (not provided)')
        # Initialize empty columns
        for c in DMS_SUBSCORE_COLS:
            df[c] = pd.NA

    # 11. Merge primer annotations (if provided)
    if args.annotations and os.path.exists(args.annotations):
        print(f'\nReading primer annotations from {args.annotations} ...')
        df_anno = pd.read_csv(args.annotations)
        print(f'  {len(df_anno):,} rows')

        # Merge key: assay_id + seq_id (or assay_id + left_primer + right_primer + template_used)
        anno_cols_present = [c for c in ANNOTATION_COLS if c in df_anno.columns]
        if anno_cols_present:
            # Try merging by assay_id + seq_id first
            if 'assay_id' in df_anno.columns and 'seq_id' in df_anno.columns:
                anno_key = ['assay_id', 'seq_id']
                for c in anno_key:
                    df[c] = df[c].astype(str)
                    df_anno[c] = df_anno[c].astype(str)
                df = df.merge(
                    df_anno[anno_key + anno_cols_present].drop_duplicates(subset=anno_key),
                    on=anno_key, how='left'
                )
                print(f'  Merged {len(anno_cols_present)} annotation columns by assay_id + seq_id')
            elif 'assay_id' in df_anno.columns:
                df_anno['_key'] = make_key(df_anno) if all(c in df_anno.columns for c in KEY_COLS) else None
                if df_anno['_key'] is not None:
                    df = df.merge(
                        df_anno[['_key'] + anno_cols_present].drop_duplicates(subset='_key'),
                        on='_key', how='left'
                    )
                    print(f'  Merged {len(anno_cols_present)} annotation columns by composite key')
                else:
                    print(f'  WARNING: could not find merge key in annotations CSV')
            else:
                print(f'  WARNING: no assay_id column in annotations CSV')
        else:
            print(f'  WARNING: no annotation columns found in {args.annotations}')
    else:
        print(f'\nSkipping primer annotations (not provided)')
        # Initialize empty columns
        for c in ANNOTATION_COLS:
            df[c] = pd.NA

    # 12. Drop merge key
    df = df.drop(columns=['_key'])

    # 13. Update sheets
    all_sheets['All_Primers'] = df

    # Create Selected_Panel sheet (selected rows with all columns)
    selected_panel = df[df['selected_for_panel'] == 1].copy()
    all_sheets['Selected_Panel'] = selected_panel

    # 14. Build and add Data_Dictionary sheet
    print('\nBuilding data dictionary ...')
    df_dict = build_data_dictionary()
    all_sheets['Data_Dictionary'] = df_dict
    print(f'  Data_Dictionary: {len(df_dict)} rows')

    # 15. Write output xlsx
    print(f'\nWriting {args.output} ...')
    print(f'  All_Primers:      {len(df):,} rows x {len(df.columns)} cols')
    print(f'  Selected_Panel:   {len(selected_panel):,} rows')
    print(f'  Data_Dictionary:  {len(df_dict)} rows')
    for name in sheet_names:
        if name != 'All_Primers':
            print(f'  {name}: {len(all_sheets[name]):,} rows (preserved)')

    try:
        with pd.ExcelWriter(args.output, engine='xlsxwriter') as writer:
            for sheet_name, df_sheet in all_sheets.items():
                df_sheet.to_excel(writer, sheet_name=sheet_name, index=False)
            # Format the Data_Dictionary sheet with wider columns
            ws = writer.sheets['Data_Dictionary']
            ws.set_column('A:A', 35)  # Sheet
            ws.set_column('B:B', 5)   # No
            ws.set_column('C:C', 30)  # Column
            ws.set_column('D:D', 15)  # Type
            ws.set_column('E:E', 80)  # Description
            ws.set_column('F:F', 40)  # Example_Values
        engine_used = 'xlsxwriter'
    except Exception as e:
        print(f'  xlsxwriter failed ({e}), falling back to openpyxl ...', file=sys.stderr)
        with pd.ExcelWriter(args.output, engine='openpyxl') as writer:
            for sheet_name, df_sheet in all_sheets.items():
                df_sheet.to_excel(writer, sheet_name=sheet_name, index=False)
        engine_used = 'openpyxl'

    elapsed = time.time() - t0
    file_mb = os.path.getsize(args.output) / 1e6

    print(f'\nDone in {elapsed:.0f}s ({engine_used})')
    print(f'Output: {args.output} ({file_mb:.0f} MB)')

    # Summary
    n_screened = df['ePCR_verdict'].notna().sum()
    n_pass = (df['ePCR_verdict'] == 'PASS').sum()
    n_fail = (df['ePCR_verdict'] == 'FAIL').sum()
    n_wrong = df['ePCR_error'].astype(str).str.contains('wrong_genome', na=False).sum()
    n_not_spec = df['ePCR_error'].astype(str).str.contains('not_methylation_specific', na=False).sum()
    n_selected = df['selected_for_panel'].sum()

    print(f'\n{"="*60}')
    print(f'SUMMARY')
    print(f'{"="*60}')
    print(f'  Total atlas rows:     {len(df):,}')
    print(f'  Screened:             {n_screened:,}')
    print(f'    PASS:               {n_pass:,}')
    print(f'    FAIL:               {n_fail:,}')
    print(f'      wrong_genome:     {n_wrong:,}')
    print(f'      not_meth_spec:    {n_not_spec:,}')
    print(f'  Selected for panel:   {n_selected:,}')
    print(f'  Unscreened:           {len(df) - n_screened:,}')
    print(f'  Sheets:               {list(all_sheets.keys())}')


if __name__ == '__main__':
    main()
